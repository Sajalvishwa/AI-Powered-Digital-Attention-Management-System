import uuid
from datetime import datetime, timedelta, timezone

from pydantic import BaseModel, ConfigDict, Field, model_validator


class ActivitySessionIn(BaseModel):
    """One continuous stretch in one app (or idle), sent by the desktop agent."""

    client_id: uuid.UUID  # generated by the agent; makes uploads idempotent
    app_name: str = Field(min_length=1, max_length=255)
    window_title: str | None = Field(default=None, max_length=1000)
    is_idle: bool = False
    started_at: datetime
    ended_at: datetime
    focus_session_id: uuid.UUID | None = None

    @model_validator(mode="after")
    def check_times(self) -> "ActivitySessionIn":
        for name in ("started_at", "ended_at"):
            value = getattr(self, name)
            if value.tzinfo is None or value.utcoffset() is None:
                raise ValueError(f"{name} must include a timezone, e.g. 2026-10-11T10:00:00Z")
        if self.ended_at < self.started_at:
            raise ValueError("ended_at must be >= started_at")
        if self.ended_at > datetime.now(timezone.utc) + timedelta(days=1):
            raise ValueError("ended_at is too far in the future")
        return self


class ActivityBatchIn(BaseModel):
    sessions: list[ActivitySessionIn] = Field(min_length=1, max_length=500)


class ActivityBatchOut(BaseModel):
    received: int
    inserted: int
    duplicates: int  # already uploaded earlier (same client_id) -> ignored safely
    skipped: int  # apps in the user's ignore-list


class ActivitySessionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    client_id: uuid.UUID
    app_name: str
    window_title: str | None
    is_idle: bool
    started_at: datetime
    ended_at: datetime
    duration_sec: int | None
    focus_session_id: uuid.UUID | None
